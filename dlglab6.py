import numpy as np
from IPython.display import Audio, display

# 1. Audio settings
sample_rate = 44100   # Standard CD audio quality (Hz)
note_duration = 0.25  # Duration of each note in seconds (adjust for speed)

# 2. Convert each note token (0–49) into a musical frequency (Hz)
# Mapping token 0 to MIDI note 48 (C3) up to token 49 -> MIDI note 97 (C#7)
audio_waveform = np.array([], dtype=np.float32)

for note_token in generated_music:
    midi_pitch = note_token + 48
    freq = 440.0 * (2.0 ** ((midi_pitch - 69) / 12.0))  # Convert MIDI pitch to Hz

    # Generate a smooth tone for this note (with brief fade-in/out to prevent clicking)
    t = np.linspace(0, note_duration, int(sample_rate * note_duration), endpoint=False)
    envelope = np.minimum(t * 50, 1.0) * np.minimum((note_duration - t) * 50, 1.0)
    tone = 0.4 * envelope * np.sin(2 * np.pi * freq * t)

    audio_waveform = np.concatenate((audio_waveform, tone))

# 3. Display the playable audio bar in Colab
display(Audio(audio_waveform, rate=sample_rate))

