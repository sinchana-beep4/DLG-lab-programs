# Implement forward propagation with ReLU for hidden layers and softmax for output.
def relu(Z):
    return np.maximum(0, Z)

def relu_derivative(Z):
    return (Z > 0).astype(float)

def softmax(Z):
    # Subtract max for numerical stability
    Z_shifted = Z - np.max(
        Z,
        axis=1,
        keepdims=True
    )
    exp_Z = np.exp(Z_shifted)
    probabilities = (
        exp_Z /
        np.sum(exp_Z, axis=1, keepdims=True)
    )
    return probabilities

def forward_propagation(X, parameters):

    W1 = parameters["W1"]
    b1 = parameters["b1"]

    W2 = parameters["W2"]
    b2 = parameters["b2"]

    W3 = parameters["W3"]
    b3 = parameters["b3"]

    W4 = parameters["W4"]
    b4 = parameters["b4"]

    # Layer 1
    Z1 = X @ W1 + b1
    A1 = relu(Z1)

    # Layer 2
    Z2 = A1 @ W2 + b2
    A2 = relu(Z2)

    # Layer 3
    Z3 = A2 @ W3 + b3
    A3 = relu(Z3)

    # Output layer
    Z4 = A3 @ W4 + b4

    # Softmax
    Y_hat = softmax(Z4)

    cache = {
        "X": X,
        "Z1": Z1,
        "A1": A1,
        "Z2": Z2,
        "A2": A2,
        "Z3": Z3,
        "A3": A3,
        "Z4": Z4,
        "Y_hat": Y_hat
    }

    return Y_hat, cache

# Compute weighted categorical cross-entropy loss.
def compute_loss(Y, Y_hat, class_weight_array):

    # Find the class of each sample
    true_classes = np.argmax(Y, axis=1)

    # Weight corresponding to true class
    sample_weights = class_weight_array[true_classes]

    # Numerical stability
    epsilon = 1e-15

    Y_hat_clipped = np.clip(
        Y_hat,
        epsilon,
        1 - epsilon
    )

    # Categorical cross entropy
    cross_entropy = -np.sum(
        Y * np.log(Y_hat_clipped),
        axis=1
    )

    # Apply class weights
    weighted_loss = (
        sample_weights * cross_entropy
    )

    return np.mean(weighted_loss)

# Implement backpropagation with class weights applied to gradients.
def backward_propagation(
    Y,
    Y_hat,
    cache,
    parameters,
    class_weight_array
):

    X = cache["X"]

    Z1 = cache["Z1"]
    A1 = cache["A1"]

    Z2 = cache["Z2"]
    A2 = cache["A2"]

    Z3 = cache["Z3"]
    A3 = cache["A3"]

    W1 = parameters["W1"]
    W2 = parameters["W2"]
    W3 = parameters["W3"]
    W4 = parameters["W4"]

    B = X.shape[0]

    true_classes = np.argmax(Y, axis=1)

    sample_weights = class_weight_array[true_classes]

    sample_weights = sample_weights.reshape(-1, 1)

    dZ4 = (
        sample_weights *
        (Y_hat - Y)
    ) / B

    dW4 = A3.T @ dZ4

    db4 = np.sum(
        dZ4,
        axis=0,
        keepdims=True
    )

    dA3 = dZ4 @ W4.T

    dZ3 = (
        dA3 *
        relu_derivative(Z3)
    )

    dW3 = A2.T @ dZ3

    db3 = np.sum(
        dZ3,
        axis=0,
        keepdims=True
    )

    dA2 = dZ3 @ W3.T

    dZ2 = (
        dA2 *
        relu_derivative(Z2)
    )

    dW2 = A1.T @ dZ2

    db2 = np.sum(
        dZ2,
        axis=0,
        keepdims=True
    )

    dA1 = dZ2 @ W2.T

    dZ1 = (
        dA1 *
        relu_derivative(Z1)
    )

    dW1 = X.T @ dZ1

    db1 = np.sum(
        dZ1,
        axis=0,
        keepdims=True
    )

    gradients = {

        "dW1": dW1,
        "db1": db1,

        "dW2": dW2,
        "db2": db2,

        "dW3": dW3,
        "db3": db3,

        "dW4": dW4,
        "db4": db4
    }

    return gradients

def update_parameters(
    parameters,
    gradients,
    learning_rate
):

    for l in range(1, 5):

        parameters[f"W{l}"] -= (
            learning_rate *
            gradients[f"dW{l}"]
        )

        parameters[f"b{l}"] -= (
            learning_rate *
            gradients[f"db{l}"]
        )

    return parameters

def predict(X, parameters):

    Y_hat, _ = forward_propagation(
        X,
        parameters
    )

    predictions = np.argmax(
        Y_hat,
        axis=1
    )

    return predictions, Y_hat

