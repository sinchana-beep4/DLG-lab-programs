#Initialize parameters using He initialization for ReLU: W(l) ∼ N (0,root(2/nl−1)).
def initialize_parameters(layer_sizes):

    parameters = {}

    for l in range(1, len(layer_sizes)):

        n_previous = layer_sizes[l - 1]
        n_current = layer_sizes[l]

        # He initialization
        parameters[f"W{l}"] = (
            np.random.randn(n_previous, n_current)
            * np.sqrt(2 / n_previous)
        )

        parameters[f"b{l}"] = np.zeros((1, n_current))

    return parameters


